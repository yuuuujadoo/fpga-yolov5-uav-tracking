`timescale 1ns / 1ps
//////////////////////////////////////////////////////////////////////////////////
// 모듈명: data_formatter (2048-bit Unpacker & Coordinate Generator)
// 역할: 
//   1. 상위 제어기(Wrapper)로부터 시작 명령(i_start)과 레이어 설정값(해상도, 주소)을 받습니다.
//   2. 2048-bit 안에는 8개의 픽셀(각 32채널/256-bit)이 패딩되어 저장되어 있습니다.
//   3. 각 256-bit 조각에서 실제 데이터인 18채널(144-bit)만 추출합니다.
//   4. 잘라낸 데이터가 영상의 어느 좌표(cx, cy)와 어느 앵커(0~2)에 해당하는지 계산하여 묶어줍니다.
//////////////////////////////////////////////////////////////////////////////////

module data_formatter #(
    // =========================================================================
    // [정적 파라미터 선언부] 하드웨어가 합성될 때 크기를 결정짓는 불변의 상수들입니다.
    // =========================================================================
    parameter DATA_WIDTH   = 8,          // 1개의 파라미터(예: tx)가 가지는 비트 수 (INT8 양자화이므로 8-bit)
    parameter CHANNELS     = 6,          // 1개의 앵커가 필요로 하는 파라미터 개수 (tx, ty, tw, th, conf, cls = 총 6개)
    parameter PIXEL_BITS   = 256,        // 메모리상에서 1개 픽셀이 차지하는 총 비트 수 (32채널 * 8비트 = 256-bit)
    parameter GB_BUS_WIDTH = 2048,       // Global Buffer와 데이터를 주고받는 초광대역 버스의 비트 폭 (2048-bit)
    parameter ADDR_WIDTH   = 15          // Global Buffer의 메모리 주소를 표현하기 위한 주소선의 비트 폭
)(
    // =========================================================================
    // [1. 시스템 공통 신호] 모든 모듈이 공유하는 맥박과 초기화 버튼입니다.
    // =========================================================================
    input  wire                                clk,           // 100MHz 등으로 진동하는 시스템 메인 클럭
    input  wire                                rst_n,         // Active-Low 리셋 신호 (0이 들어오면 모든 상태가 초기화됨)

    // =========================================================================
    // [2. 상위 제어 신호] Top Wrapper 모듈에서 런타임에 동적으로 넣어주는 파라미터들입니다.
    // =========================================================================
    input  wire                                i_start,       // 레이어(P3 또는 P4) 처리를 지금 당장 시작하라는 방아쇠(Trigger) 신호
    input  wire [ADDR_WIDTH-1:0]               i_base_addr,   // GFB 내에서 현재 레이어 데이터가 저장된 시작 번지수
    input  wire [7:0]                          i_grid_w,      // 현재 레이어의 가로 픽셀 개수 (P3면 80, P4면 40)
    input  wire [7:0]                          i_grid_h,      // 현재 레이어의 세로 픽셀 개수 (P3면 80, P4면 40)
    
    // [상태 출력 신호]
    output reg                                 o_done,        // 전체 해상도 처리가 100% 완료되었음을 Top FSM에게 보고하는 신호

    // =========================================================================
    // [3. Global Buffer (BRAM) 인터페이스] 메모리에서 데이터를 읽어오기 위한 선들입니다.
    // =========================================================================
    output reg                                 o_gb_ren,      // BRAM에게 "데이터를 읽겠다"고 알리는 읽기 활성화(Read Enable) 핀
    output reg  [ADDR_WIDTH-1:0]               o_gb_raddr,    // BRAM에게 "이 주소에 있는 걸 줘"라고 요구하는 주소 핀
    input  wire [GB_BUS_WIDTH-1:0]             i_gb_rdata,    // BRAM에서 1클럭의 지연을 거친 후 쏟아져 들어오는 2048-bit 거대 데이터 핀
    input  wire                                i_gb_rvalid,   // 지금 i_gb_rdata 선에 실린 데이터가 쓰레기값이 아니라 '진짜 유효한 데이터'임을 알리는 핀

    // =========================================================================
    // [4. 다운스트림 (Splitter) 인터페이스] 썰어낸 데이터를 다음 단으로 넘겨주는 선들입니다.
    // =========================================================================
    input  wire                                ready_in,      // 뒤쪽 통신망(FIFO)이 꽉 찼을 때 0이 되어, 썰기 작업을 일시정지(Freeze)시키는 방어 신호
    output reg                                 o_split_valid, // 지금 썰어서 내보내는 48-bit 데이터가 진짜임을 알리는 유효 신호
    output reg  [47:0]                         o_split_data,  // 예쁘게 6채널(48-bit)로 썰어낸 알맹이 데이터 묶음
    output reg  [7:0]                          o_split_cx,    // 지금 썰어낸 데이터가 원본 이미지의 가로 몇 번째(X) 픽셀인지 알려주는 좌표
    output reg  [7:0]                          o_split_cy,    // 지금 썰어낸 데이터가 원본 이미지의 세로 몇 번째(Y) 픽셀인지 알려주는 좌표
    output reg  [1:0]                          o_split_anchor // 지금 썰어낸 데이터가 0, 1, 2번 앵커 중 누구의 것인지 알려주는 식별자
);

    // =========================================================================
    // [FSM 상태 정의부] 하드웨어가 가질 수 있는 5가지 상태를 명확히 정의합니다.
    // =========================================================================
    localparam S_IDLE  = 3'd0; // 아무 일도 하지 않고 i_start 신호만 쳐다보고 있는 '대기 상태'
    localparam S_REQ   = 3'd1; // BRAM에게 읽고 싶은 주소를 던져주는 '요청 상태'
    localparam S_WAIT  = 3'd2; // BRAM이 데이터를 찾아서 내뱉을 때까지 1클럭을 소모하며 멍때리는 '대기 상태'
    localparam S_PIXEL = 3'd3; // 들어온 2048-bit 데이터를 48-bit씩 가위질해서 넘겨주는 '노동(썰기) 상태'
    localparam S_DONE  = 3'd4; // 영상 전체(예: 80x80)를 모두 처리하고 끝났음을 알리는 '완료 상태'

    // =========================================================================
    // [내부 레지스터 선언부] 상태와 숫자를 기억할 플립플롭(Flip-Flop) 그릇들입니다.
    // =========================================================================
    reg [2:0] state, next_state;          // state: 지금 내 상태, next_state: 다음 클럭에 바뀔 상태
    reg [GB_BUS_WIDTH-1:0] line_buffer;   // 2048-bit라는 엄청난 크기의 데이터를 꿀꺽 삼켜서 저장해 둘 초거대 버퍼
    reg [2:0] pixel_idx;                  // 2048-bit 버퍼 안에는 총 8개의 픽셀이 있습니다. 그중 몇 번째를 썰고 있는지 세는 카운터 (0~7)
    reg [1:0] anchor_idx;                 // 1개 픽셀 안에는 3개의 앵커가 있습니다. 그중 몇 번째 앵커를 썰고 있는지 세는 카운터 (0~2)
    reg [7:0] cx, cy;                     // 화면 전체(예: 80x80) 기준으로 내가 지금 어디쯤을 썰고 있는지 기억하는 X, Y 좌표 내비게이션
    reg [ADDR_WIDTH-1:0] addr_offset;     // base_addr로부터 시작해서 2048-bit씩 몇 번이나 긁어왔는지 책갈피를 꽂아두는 오프셋 카운터

    // =========================================================================
    // [always 블록: 1. FSM 상태 전이 (순차 회로)]
    // 설명: 오직 클럭(clk)의 상승 에지마다 동작하며, 다음 상태(next_state)를 현재 상태(state)로 덮어씁니다.
    // =========================================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            // 리셋 버튼이 눌리면 하던 일을 모두 멈추고 강제로 IDLE(대기) 상태로 돌아갑니다.
            state <= S_IDLE;
        end else begin
            // 평소에는 조합 회로가 결정해 둔 길(next_state)을 따라 한 발짝 이동합니다.
            state <= next_state;
        end
    end

    // =========================================================================
    // [always 블록: 2. 다음 상태 결정 (조합 회로)]
    // 설명: 현재 상태와 주변의 신호 상황을 보고, 다음에 어디로 가야 할지 이정표를 세웁니다.
    // =========================================================================
    always @(*) begin
        // 의도치 않은 래치(Latch)가 생기는 것을 막기 위해, 기본적으로는 '현재 상태 유지'로 설정해 둡니다.
        next_state = state; 
        
        case (state)
            S_IDLE: begin
                // IDLE 상태일 때, Top에서 일하라고 i_start를 1로 주면 REQ 상태로 전이합니다.
                if (i_start) next_state = S_REQ;
            end
            
            S_REQ: begin
                // 주소를 BRAM 핀에 올렸으므로, 답변이 올 때까지 기다리기 위해 무조건 WAIT 상태로 넘어갑니다.
                next_state = S_WAIT;
            end
            
            S_WAIT: begin
                // BRAM에서 "데이터 찾았어!(rvalid=1)"라고 신호가 오면, 고기를 썰기 위해 PIXEL 상태로 넘어갑니다.
                if (i_gb_rvalid) next_state = S_PIXEL;
            end
            
            S_PIXEL: begin
                // 뒷단 모듈(또는 FIFO)이 데이터 받을 준비가 되었을 때(ready_in == 1)만 상태를 넘깁니다. 
                // (ready_in == 0 이면 계속 PIXEL 상태에 머물며 멈춰있습니다)
                if (ready_in) begin
                    // 버퍼 안의 마지막 8번째 픽셀(idx=7)의 마지막 3번째 앵커(idx=2)까지 썰기를 완료했을 때의 조건입니다.
                    if (pixel_idx == 3'd7 && anchor_idx == 2'd2) begin
                        
                        // 현재 내 좌표가 화면의 맨 끝자락(가로 끝, 세로 끝)에 도달했다면 모든 레이어 연산이 끝난 것입니다.
                        if (cx == i_grid_w - 1 && cy == i_grid_h - 1) 
                            // 완료 상태(DONE)로 전이합니다.
                            next_state = S_DONE;
                        else 
                            // 아직 화면을 덜 훑었다면, 다음 2048-bit 덩어리를 메모리에서 더 가져오기 위해 REQ 상태로 돌아갑니다.
                            next_state = S_REQ;
                    end
                end
            end
            
            S_DONE: begin
                // 완료 신호를 1클럭 동안 띄워준 후, 다음 레이어(예: P4) 명령을 받기 위해 다시 IDLE로 돌아갑니다.
                next_state = S_IDLE;
            end
            
            default: begin
                // 설계상 도달할 수 없는 이상한 상태로 꼬일 경우를 대비한 안전망입니다.
                next_state = S_IDLE;
            end
        endcase
    end

    // =========================================================================
    // [always 블록: 3. 실제 데이터 처리 및 카운터 제어 (순차 회로)]
    // 설명: 상태(state)에 따라 메모리에 읽기 요청을 하고, 버퍼를 가위질하며, 모든 카운터를 증가시킵니다.
    // =========================================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            // 전원이 켜지거나 리셋이 들어오면 모든 출력 핀과 내부 카운터, 버퍼를 완벽한 0으로 초기화합니다.
            o_gb_ren <= 0; o_gb_raddr <= 0; addr_offset <= 0;
            pixel_idx <= 0; anchor_idx <= 0; cx <= 0; cy <= 0;
            o_split_valid <= 0; o_split_data <= 0;
            o_split_cx <= 0; o_split_cy <= 0; o_split_anchor <= 0;
            o_done <= 0; line_buffer <= 0;
        end else begin
            case (state)
                
                S_IDLE: begin
                    // 대기 상태에서는 이전 레이어(P3)에서 쓰던 좌표나 오프셋이 남아있으면 안 되므로 모두 청소해 줍니다.
                    o_done <= 0; addr_offset <= 0; cx <= 0; cy <= 0;
                    pixel_idx <= 0; anchor_idx <= 0;
                    o_split_valid <= 0;
                end

                S_REQ: begin
                    // BRAM에게 데이터를 내놓으라고 Read Enable 핀을 1로 켭니다.
                    o_gb_ren <= 1'b1;
                    // 시작 주소(base_addr)에 책갈피(addr_offset)를 더해서 실제로 읽어올 물리 주소를 만듭니다.
                    o_gb_raddr <= i_base_addr + addr_offset;
                    // 다음 요청 때는 한 줄 밑의 데이터를 읽어야 하므로 오프셋을 1 증가시켜 둡니다.
                    addr_offset <= addr_offset + 1;
                    
                    // 아직 읽어오는 중이므로 내보낼 썰린 데이터가 없습니다. 유효 신호를 꺼둡니다.
                    o_split_valid <= 0; 
                end

                S_WAIT: begin
                    // BRAM이 똑같은 주소를 여러 번 읽는 것을 방지하기 위해 Read Enable을 즉시 0으로 내립니다.
                    o_gb_ren <= 1'b0; 
                    
                    // 메모리에서 진짜 데이터가 도착했다는 rvalid 신호가 뜨면
                    if (i_gb_rvalid) begin
                        // 도착한 거대한 2048-bit 덩어리를 내 뱃속(line_buffer)으로 꿀꺽 삼킵니다(Latch).
                        line_buffer <= i_gb_rdata;
                    end
                end

                S_PIXEL: begin
                    // 뒷단이 막히지 않았을 때(ready_in == 1)만 아래의 노동을 수행합니다. (파이프라인 Stall 방어)
                    if (ready_in) begin
                        
                        // "지금부터 썰어낸 48-bit 진짜니까 가져가라!" 하고 유효 신호를 켭니다.
                        o_split_valid <= 1'b1;
                        
                        // 지금 썰어내는 데이터의 꼬리표(X좌표, Y좌표, 앵커 번호)를 옆구리에 달아줍니다.
                        o_split_cx <= cx;
                        o_split_cy <= cy;
                        o_split_anchor <= anchor_idx;

                        // ★★★ [Bit Slicing 핵심 마법] 32채널 패딩 회피 기법 ★★★
                        // (pixel_idx * 256): 1픽셀은 패딩을 포함해 256비트(32채널)입니다. 픽셀 번호에 따라 큼직하게 점프합니다.
                        // (anchor_idx * 48): 진짜 데이터 구역(앞쪽 18채널) 안에서, 앵커 단위인 6채널(48비트)씩 세밀하게 점프합니다.
                        // +: 48 : 점프해서 도달한 베이스 위치에서부터 정확히 48가닥의 선을 가위로 오려내어 출력 포트에 꽂아줍니다.
                        o_split_data <= line_buffer[(pixel_idx * 256) + (anchor_idx * 48) +: 48];

                        // =====================================================================
                        // 💡 [치명적 버그 수정 완료] 카운터 업데이트 구역 (시계열 톱니바퀴)
                        // 설명: 앵커 카운터, 픽셀 좌표 카운터, 버퍼 인덱스 카운터가 완전히 독립적이고 
                        // 논리적으로 맞물려 돌아가도록 수정되었습니다.
                        // =====================================================================
                        
                        // 1. 앵커 카운터 체크 (0, 1, 2)
                        // 한 픽셀 안의 3번째 앵커(idx=2)를 방금 다 썰어냈다면, 픽셀 하나를 완전히 끝낸 것입니다!
                        if (anchor_idx == 2'd2) begin
                            // 다음 픽셀을 위해 앵커 카운터는 0으로 되감습니다.
                            anchor_idx <= 0; 
                            
                            // 💡[버그 해결 지점]: 픽셀 1개를 다 끝냈으니, 영상 좌표(cx, cy)를 즉시 이동시킵니다!
                            // 화면의 맨 우측 끝(i_grid_w - 1)에 도달했다면 타자기가 줄바꿈을 해야 합니다.
                            if (cx == i_grid_w - 1) begin
                                cx <= 0;      // X축 캐리지를 맨 왼쪽으로 되돌림
                                cy <= cy + 1; // Y축을 한 칸 아래로 내림
                            end else begin
                                // 우측 끝이 아니라면 단순히 X축으로 한 칸 우측으로 전진합니다.
                                cx <= cx + 1; 
                            end
                            
                            // 💡 버퍼 내 픽셀 인덱스 체크 (0 ~ 7)
                            // 좌표는 이동시켰고, 이제 2048-bit 버퍼 안에 남은 픽셀이 있는지 확인합니다.
                            // 8번째 픽셀(idx=7)까지 방금 다 파먹었다면
                            if (pixel_idx == 3'd7) begin
                                // 다음 2048-bit 덩어리를 파먹기 위해 픽셀 인덱스를 0으로 되감습니다.
                                pixel_idx <= 0; 
                            end else begin
                                // 아직 버퍼 안에 남은 픽셀이 있다면 다음 픽셀로 인덱스를 1 증가시킵니다.
                                pixel_idx <= pixel_idx + 3'd1; 
                            end
                            
                        end else begin
                            // 한 픽셀 내에서 아직 앵커 3개를 다 못 썰었다면 앵커 번호만 1 증가시킵니다.
                            anchor_idx <= anchor_idx + 2'd1; 
                        end
                        
                    end 
                    else begin
                        // ready_in이 0일 때 (이더넷 FIFO가 가득 차서 멈추라고 할 때)
                        // 아무런 카운터도 증가시키지 않고 블록을 건너뜁니다.
                        // 플립플롭의 특성상 o_split_data와 유효 신호는 이전 클럭의 값을 그대로 유지(Hold)하게 되며,
                        // 뒷단이 다시 받을 준비가 될 때까지 데이터를 안전하게 쥐고 대기합니다.
                    end
                end

                S_DONE: begin
                    // Top FSM에게 "나 P3 레이어 (또는 P4 레이어) 모두 끝냈소!" 하고 완료 깃발을 1클럭 동안 올립니다.
                    o_done <= 1'b1; 
                    // 일이 끝났으니 더 이상 유효한 데이터가 없다고 선언합니다.
                    o_split_valid <= 1'b0;
                end
                
            endcase
