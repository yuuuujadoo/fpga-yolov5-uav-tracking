`timescale 1ns / 1ps
//////////////////////////////////////////////////////////////////////////////////
// 모듈명: sigmoid_lut_unit
// 역할: 
// - 단 1개의 8-bit 양자화 데이터를 입력받아, 미리 계산된 Sigmoid 결과값을 꺼내옵니다.
// - 수식(지수 연산, 나눗셈)을 전혀 사용하지 않고 오직 메모리 참조만 수행하므로 DSP 소모가 0입니다.
//////////////////////////////////////////////////////////////////////////////////
module sigmoid_lut #(
    // 정적 파라미터 선언 (데이터 비트 폭)
    parameter DATA_WIDTH = 8
)(
    // [시스템 공통 신호]
    input  wire                   clk,        // 메인 클럭
    input  wire                   rst_n,      // 비동기 리셋

    // [입력 포트]
    input  wire signed [7:0]      din,        // Sigmoid에 넣을 8-bit 원시 데이터 (-128 ~ 127)
    input  wire                   valid_in,   // 입력 데이터 유효 신호
    input  wire                   ready_in,   // 뒷단 파이프라인에서 오는 Stall 제어 신호

    // [출력 포트]
    output reg  signed [7:0]      dout,       // Sigmoid 처리가 끝난 8-bit 결과 (Q0.7 포맷)
    output reg                    valid_out   // 출력 데이터 유효 신호
);

    // =========================================================================
    // [메모리 배열 선언]
    // (* rom_style = "distributed" *)을 통해 FPGA의 귀중한 BRAM을 낭비하지 않고,
    // 일반 논리 소자(LUT)를 묶어서 만든 초소형 분산 램(Distributed RAM)으로 합성시킵니다.
    // =========================================================================
    (* rom_style = "distributed" *) reg [7:0] rom [0:255];

    // 하드웨어 전원이 켜지거나 시뮬레이션이 시작될 때 
    // 파이썬에서 추출한 256줄의 .mem 파일을 이 메모리 배열에 초기값으로 박아 넣습니다.
    initial begin
        $readmemh("sigmoid_int8.mem", rom);
    end

    // =========================================================================
    // [always 블록] 파이프라인 동기화 및 메모리 읽기 연산 (순차 회로)
    // 설명: 주소가 들어오면 1클럭을 소모하여 메모리 데이터를 읽어냅니다.
    // =========================================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            // 리셋 시 쓰레기 출력 차단
            dout <= 0;
            valid_out <= 0;
        end 
        else begin
            // 파이프라인이 멈추지 않았을 때(ready_in == 1)만 톱니바퀴가 돌아갑니다.
            if (ready_in) begin
                
                // 메모리에서 값을 꺼내는 데 1클럭이 걸리므로 유효 신호도 1클럭 지연시켜 넘깁니다.
                valid_out <= valid_in;
                
                // 유효한 입력이 들어왔을 때만 메모리 참조를 수행합니다.
                if (valid_in) begin
                    // [$unsigned()의 마법] 
                    // din은 부호 있는 음수를 포함(-128~127)하지만, 메모리 주소는 0~255의 양수여야 합니다.
                    // $unsigned를 씌우면 하드웨어 선 배치는 1도 안 건드리고, 컴파일러가 
                    // "아, 이건 부호를 무시하고 2의 보수 패턴 그대로 주소로 써라"라고 똑똑하게 이해합니다.
                    dout <= rom[$unsigned(din)];
                end
            end
        end
    end

endmodule